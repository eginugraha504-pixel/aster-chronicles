CREATE TABLE IF NOT EXISTS players (
  uid TEXT PRIMARY KEY, uname TEXT NOT NULL COLLATE NOCASE UNIQUE, ph TEXT NOT NULL, salt TEXT NOT NULL,
  bot INTEGER, created INTEGER NOT NULL, last INTEGER NOT NULL DEFAULT 0, ban INTEGER NOT NULL DEFAULT 0,
  sv INTEGER NOT NULL DEFAULT 0, save TEXT, lv INTEGER NOT NULL DEFAULT 1, cp INTEGER NOT NULL DEFAULT 0, prof TEXT, ov TEXT);
CREATE UNIQUE INDEX IF NOT EXISTS players_bot ON players (bot) WHERE bot IS NOT NULL;
CREATE INDEX IF NOT EXISTS players_last ON players (last);
CREATE TABLE IF NOT EXISTS sessions (tok TEXT PRIMARY KEY, uid TEXT NOT NULL, ts INTEGER NOT NULL);
CREATE INDEX IF NOT EXISTS sessions_uid ON sessions (uid);
CREATE TABLE IF NOT EXISTS friends (a TEXT NOT NULL, b TEXT NOT NULL, frm TEXT NOT NULL, st TEXT NOT NULL, ts INTEGER NOT NULL, PRIMARY KEY (a, b));
CREATE INDEX IF NOT EXISTS friends_b ON friends (b);
CREATE TABLE IF NOT EXISTS dms (id INTEGER PRIMARY KEY AUTOINCREMENT, frm TEXT NOT NULL, too TEXT NOT NULL, txt TEXT NOT NULL, ts INTEGER NOT NULL, rd INTEGER NOT NULL DEFAULT 0);
CREATE INDEX IF NOT EXISTS dms_pair ON dms (frm, too, id);
CREATE INDEX IF NOT EXISTS dms_too ON dms (too, rd);
CREATE TABLE IF NOT EXISTS wchat (id INTEGER PRIMARY KEY AUTOINCREMENT, uid TEXT NOT NULL, name TEXT NOT NULL, txt TEXT NOT NULL, ts INTEGER NOT NULL);
CREATE INDEX IF NOT EXISTS wchat_uid ON wchat (uid, id);
